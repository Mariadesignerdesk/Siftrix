import type { ScanResponse } from '../services/api'
import { clampRiskScore, formatTimestamp } from '../utils/scanPresentation'
import type { LanguageView } from '../utils/userPreferences'
import RiskGaugeRing from './RiskGaugeRing'
import { RiskLevelBadge, TargetTypeBadge, VerdictBadge } from './ScanBadges'

interface SampleReportPreviewProps {
  report: ScanResponse
  languageView: LanguageView
  onLanguageViewChange: (view: LanguageView) => void
  onClose: () => void
}

function asStringArray(value: unknown): string[] {
  if (!Array.isArray(value)) return []
  return value.filter((item): item is string => typeof item === 'string' && item.trim().length > 0)
}

function asRecord(value: unknown): Record<string, unknown> {
  return value && typeof value === 'object' && !Array.isArray(value)
    ? (value as Record<string, unknown>)
    : {}
}

export default function SampleReportPreview({
  report,
  languageView,
  onLanguageViewChange,
  onClose,
}: SampleReportPreviewProps) {
  const findings = asRecord(report.agent_findings)
  const urlAgent = asRecord(findings.url_intelligence)
  const msgAgent = asRecord(findings.message_intelligence)
  const rawMeta = asRecord(findings.raw_metadata)

  const urlIndicators = asStringArray(urlAgent.indicators)
  const msgTactics = asStringArray(msgAgent.tactics_detected)
  const extractedUrls = asStringArray(rawMeta.extracted_urls)

  const enSummary = report.summary?.en?.trim() || ''
  const urSummary = report.summary?.ur?.trim() || ''
  const enRecs = asStringArray(report.recommendations?.en)
  const urRecs = asStringArray(report.recommendations?.ur)

  const urlScore =
    typeof urlAgent.risk_score === 'number' ? clampRiskScore(urlAgent.risk_score) : null
  const msgScore =
    typeof msgAgent.risk_score === 'number' ? clampRiskScore(msgAgent.risk_score) : null

  return (
    <div
      id="scanner-sample-preview"
      role="region"
      aria-label="Illustrative Sample Threat Report Preview"
      className="relative mt-8 overflow-hidden rounded-2xl siftrix-card text-left animate-siftrix-enter"
    >
      {/* Executive Report Accent Trim */}
      <div
        aria-hidden="true"
        className="pointer-events-none h-[3px] w-full bg-gradient-to-r from-siftrix-charcoal via-siftrix-gold to-siftrix-charcoal"
      />

      {/* Illustrative Static Classification Banner */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 border-b border-siftrix-border bg-siftrix-pearl px-5 sm:px-7 py-4">
        <div className="flex flex-wrap items-center gap-2.5">
          <span className="inline-flex items-center gap-1.5 rounded-full border border-amber-200 bg-amber-50 px-3 py-1 text-[11px] font-bold uppercase tracking-[0.12em] text-amber-800">
            <span aria-hidden="true" className="h-1.5 w-1.5 rounded-full bg-amber-500" />
            <span>Illustrative Sample Report · Static Example</span>
          </span>
          <span className="text-xs text-siftrix-muted-dark">
            Format preview only — not generated by a live scan
          </span>
        </div>

        <button
          type="button"
          onClick={onClose}
          className="siftrix-command-pill self-start sm:self-center rounded-lg px-3 py-1.5 text-xs font-semibold cursor-pointer focus:outline-none focus-visible:ring-2 focus-visible:ring-siftrix-gold"
        >
          Close Preview
        </button>
      </div>

      <div className="p-5 sm:p-7 space-y-6 bg-white">
        {/* Executive Verdict + Risk Score Visualization */}
        <div className="flex flex-col lg:flex-row lg:items-stretch justify-between gap-5 pb-6 border-b border-siftrix-border">
          <div className="flex-1 space-y-4 min-w-0">
            <div className="flex flex-wrap items-center gap-2">
              <VerdictBadge verdict={report.verdict} />
              <RiskLevelBadge riskLevel={report.risk_level} />
              <TargetTypeBadge targetType={report.target_type} />
              <span className="rounded-full border border-siftrix-border bg-siftrix-pearl px-2.5 py-1 text-[11px] font-mono text-siftrix-muted-dark">
                ID: {report.id}
              </span>
            </div>

            <div>
              <h3 className="text-xl sm:text-2xl font-bold text-siftrix-charcoal tracking-tight">
                Multi-Agent Threat Intelligence Report
              </h3>
              <p className="mt-1 text-xs text-siftrix-muted-dark">
                Example timestamp: {formatTimestamp(report.created_at)} · Dual-language EN / اردو remediation
              </p>
            </div>

            {/* Scanned Sample Artifact Container */}
            <div className="rounded-xl border border-siftrix-border border-l-4 border-l-red-600 bg-[#1B1B20] p-3.5 sm:p-4 text-siftrix-pearl">
              <div className="flex flex-wrap items-center justify-between gap-2 mb-1.5">
                <span className="text-[11px] font-semibold uppercase tracking-[0.12em] text-siftrix-champagne">
                  Sample Inspected Artifact
                </span>
                <span className="text-[11px] font-medium text-[#ACA69E]">Channel: email</span>
              </div>
              <pre className="whitespace-pre-wrap break-words font-mono text-xs text-[#EBE5DA] leading-relaxed">
                {report.target_content}
              </pre>
            </div>
          </div>

          <RiskGaugeRing
            score={report.overall_risk_score}
            verdict={report.verdict}
            label="Risk Index (Sample)"
            ariaLabel="Sample risk score visualization"
          />
        </div>

        {/* Language Toggle Bar + Bilingual Executive Assessment */}
        <section className="space-y-4" aria-label="Sample Executive Assessment">
          <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3">
            <div>
              <h4 className="text-sm font-bold uppercase tracking-[0.12em] text-siftrix-charcoal">
                Executive Threat Assessment
              </h4>
              <p className="text-xs text-siftrix-muted-dark mt-0.5">
                Clear human-readable summary synthesized by Security Advisor
              </p>
            </div>

            <div
              role="group"
              aria-label="Sample report language view"
              className="inline-flex rounded-xl border border-siftrix-border bg-siftrix-pearl p-1 self-start"
            >
              {(
                [
                  { id: 'all', label: 'Both (EN + اردو)' },
                  { id: 'en', label: 'English' },
                  { id: 'ur', label: 'اردو' },
                ] as const
              ).map((option) => (
                <button
                  key={option.id}
                  type="button"
                  aria-pressed={languageView === option.id}
                  onClick={() => onLanguageViewChange(option.id)}
                  className={`rounded-lg px-3 py-1 text-xs font-semibold transition-colors cursor-pointer focus:outline-none focus-visible:ring-2 focus-visible:ring-siftrix-gold ${
                    languageView === option.id
                      ? 'bg-siftrix-charcoal text-siftrix-champagne shadow-2xs'
                      : 'text-siftrix-muted-dark hover:text-siftrix-graphite'
                  }`}
                >
                  {option.label}
                </button>
              ))}
            </div>
          </div>

          <div
            className={`grid gap-4 ${
              languageView === 'all' ? 'grid-cols-1 md:grid-cols-2' : 'grid-cols-1'
            }`}
          >
            {languageView === 'all' || languageView === 'en' ? (
              <div
                lang="en"
                dir="ltr"
                className="rounded-xl border border-siftrix-border bg-siftrix-pearl p-4 sm:p-5"
              >
                <span className="inline-block text-[11px] font-semibold uppercase tracking-[0.14em] text-siftrix-antique-ink mb-2">
                  English Summary
                </span>
                <p className="text-sm text-siftrix-graphite leading-relaxed">{enSummary}</p>
              </div>
            ) : null}

            {languageView === 'all' || languageView === 'ur' ? (
              <div
                lang="ur"
                dir="rtl"
                className="rounded-xl border border-siftrix-border bg-siftrix-pearl p-4 sm:p-5 text-right"
              >
                <span className="inline-block text-[11px] font-semibold text-siftrix-antique-ink mb-2">
                  اردو خلاصہ
                </span>
                <p className="text-sm sm:text-[15px] text-siftrix-graphite leading-loose">
                  {urSummary}
                </p>
              </div>
            ) : null}
          </div>
        </section>

        {/* Organized 3-Agent Threat Intelligence Breakdown */}
        <section className="space-y-3" aria-label="Sample Agent Intelligence Modules">
          <h4 className="text-sm font-bold uppercase tracking-[0.12em] text-siftrix-charcoal">
            Orchestrated Threat Intelligence Sections
          </h4>

          <div className="grid grid-cols-1 lg:grid-cols-3 gap-4">
            {/* Module 1: URL Intelligence */}
            <div className="rounded-xl border border-siftrix-border bg-siftrix-pearl/70 p-4 space-y-3">
              <div className="flex items-start justify-between gap-2">
                <div>
                  <p className="text-xs font-bold text-siftrix-charcoal">URL Intelligence</p>
                  <p className="text-[11px] text-siftrix-muted-dark">URLSecurityAgent</p>
                </div>
                {urlScore !== null ? (
                  <span className="rounded-full border border-red-200 bg-red-50 px-2.5 py-0.5 text-[11px] font-semibold text-red-700 siftrix-tabular">
                    Score {urlScore}/100
                  </span>
                ) : null}
              </div>

              {extractedUrls.length > 0 ? (
                <div className="rounded-lg border border-red-200/80 bg-red-50/70 p-2.5">
                  <span className="block text-[10px] font-semibold uppercase tracking-wider text-siftrix-muted-dark mb-1">
                    Extracted Link
                  </span>
                  <p className="font-mono text-[11px] text-red-700 break-all">
                    {extractedUrls[0]}
                  </p>
                </div>
              ) : null}

              <ul className="space-y-1.5 text-xs text-siftrix-muted-dark">
                {urlIndicators.map((indicator, idx) => (
                  <li key={idx} className="flex items-start gap-2">
                    <span
                      aria-hidden="true"
                      className="mt-1.5 h-1.5 w-1.5 shrink-0 rounded-full bg-red-600"
                    />
                    <span>{indicator}</span>
                  </li>
                ))}
              </ul>
            </div>

            {/* Module 2: Message Intelligence */}
            <div className="rounded-xl border border-siftrix-border bg-siftrix-pearl/70 p-4 space-y-3">
              <div className="flex items-start justify-between gap-2">
                <div>
                  <p className="text-xs font-bold text-siftrix-charcoal">Message Intelligence</p>
                  <p className="text-[11px] text-siftrix-muted-dark">MessageAnalysisAgent</p>
                </div>
                {msgScore !== null ? (
                  <span className="rounded-full border border-amber-200 bg-amber-50 px-2.5 py-0.5 text-[11px] font-semibold text-amber-800 siftrix-tabular">
                    Score {msgScore}/100
                  </span>
                ) : null}
              </div>

              <div className="rounded-lg border border-siftrix-border bg-white p-2.5">
                <span className="block text-[10px] font-semibold uppercase tracking-wider text-siftrix-muted-dark mb-1">
                  Social Engineering Signals
                </span>
                <p className="text-xs text-siftrix-graphite font-medium">
                  High-urgency impersonation &amp; credential lure structure
                </p>
              </div>

              <ul className="space-y-1.5 text-xs text-siftrix-muted-dark">
                {msgTactics.map((tactic, idx) => (
                  <li key={idx} className="flex items-start gap-2">
                    <span
                      aria-hidden="true"
                      className="mt-1.5 h-1.5 w-1.5 shrink-0 rounded-full bg-amber-500"
                    />
                    <span>{tactic}</span>
                  </li>
                ))}
              </ul>
            </div>

            {/* Module 3: Security Advisor & Mitigations */}
            <div className="rounded-xl border border-siftrix-border bg-siftrix-pearl/70 p-4 space-y-3">
              <div className="flex items-start justify-between gap-2">
                <div>
                  <p className="text-xs font-bold text-siftrix-charcoal">Security Advisor</p>
                  <p className="text-[11px] text-siftrix-muted-dark">SecurityAdvisorAgent</p>
                </div>
                <span className="rounded-full border border-emerald-200 bg-emerald-50 px-2.5 py-0.5 text-[11px] font-semibold text-emerald-700">
                  Action Plan
                </span>
              </div>

              <div className="space-y-2.5">
                {languageView === 'all' || languageView === 'en' ? (
                  <ul className="space-y-1.5 text-xs text-siftrix-graphite">
                    {enRecs.map((rec, idx) => (
                      <li key={idx} className="flex items-start gap-2">
                        <span className="text-emerald-700 font-bold shrink-0">✓</span>
                        <span>{rec}</span>
                      </li>
                    ))}
                  </ul>
                ) : null}

                {languageView === 'all' || languageView === 'ur' ? (
                  <ul
                    lang="ur"
                    dir="rtl"
                    className="space-y-1.5 text-xs text-siftrix-graphite text-right border-t border-siftrix-border pt-2 leading-relaxed"
                  >
                    {urRecs.map((rec, idx) => (
                      <li key={idx} className="flex items-start gap-2">
                        <span className="text-emerald-700 font-bold shrink-0">✓</span>
                        <span>{rec}</span>
                      </li>
                    ))}
                  </ul>
                ) : null}
              </div>
            </div>
          </div>
        </section>

        {/* Bottom Honest Footer Disclaimer */}
        <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-2 border-t border-siftrix-border pt-4 text-[11px] text-siftrix-muted-dark">
          <span>
            Static illustrative fixture demonstrating report layout and bilingual security guidance.
          </span>
          <span className="font-mono text-siftrix-graphite font-medium">
            Live Endpoint: POST /api/scan
          </span>
        </div>
      </div>
    </div>
  )
}
